-- AI PPT generation jobs. Presenton is the render engine; this table owns product lifecycle.

CREATE TABLE IF NOT EXISTS ppt_jobs (
    job_id VARCHAR(64) NOT NULL,
    user_id BIGINT UNSIGNED NOT NULL,
    title VARCHAR(512) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'queued',
    progress INT NOT NULL DEFAULT 0,
    message VARCHAR(1024) NULL,
    topic LONGTEXT NULL,
    source_text LONGTEXT NULL,
    file_ids_json LONGTEXT NULL,
    lang VARCHAR(16) NULL,
    page_range VARCHAR(32) NULL,
    detail VARCHAR(64) NULL,
    scene VARCHAR(64) NULL,
    tone VARCHAR(64) NULL,
    text_model_id VARCHAR(128) NULL,
    auto_img TINYINT(1) NOT NULL DEFAULT 0,
    web_search TINYINT(1) NOT NULL DEFAULT 0,
    template_id VARCHAR(64) NULL,
    page_count INT NULL,
    estimated_points INT NOT NULL DEFAULT 0,
    points_cost INT NULL,
    presenton_task_id VARCHAR(128) NULL,
    presenton_presentation_id VARCHAR(128) NULL,
    presenton_path VARCHAR(1024) NULL,
    storage_key VARCHAR(768) NULL,
    file_name VARCHAR(512) NULL,
    preview_urls_json LONGTEXT NULL,
    error_message VARCHAR(2048) NULL,
    cancelled TINYINT(1) NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    finished_at DATETIME(6) NULL,
    PRIMARY KEY (job_id),
    KEY idx_ppt_jobs_user_created (user_id, created_at),
    KEY idx_ppt_jobs_user_status_created (user_id, status, created_at),
    CONSTRAINT fk_ppt_jobs_user
        FOREIGN KEY (user_id) REFERENCES user_accounts (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
