-- V25: video generation.
--
-- This migration originally lived on the video branch as V17. That number is already used here by
-- site banners, so the merged history runs the video schema after the New API and admin migrations.
--
-- The async_tasks table itself was created in V1 and is reused rather than duplicated: it already
-- models "a long running job owned by an account" and carries the (user_id, created_at) and
-- (status, updated_at) indexes the poller needs.

-- --------------------------------------------------------------------------------------------
-- Public task identifier.
--
-- The numeric primary key is never exposed: handing it out leaks how many jobs exist and makes
-- enumeration trivial. Every lookup goes through this column, which is generated by the
-- application and unique across all task types.
-- --------------------------------------------------------------------------------------------
ALTER TABLE async_tasks
    ADD COLUMN task_key VARCHAR(64) NULL AFTER task_type,
    ADD UNIQUE KEY uk_async_tasks_key (task_key);

-- --------------------------------------------------------------------------------------------
-- Video supplier.
--
-- The key is deliberately left empty: it is supplied per environment through LLM_VIDEO_API_KEY or
-- by the admin console, exactly like the image supplier. A model bound to this provider without a
-- key fails the job with an explicit "not configured" message instead of reaching the gateway.
-- --------------------------------------------------------------------------------------------
