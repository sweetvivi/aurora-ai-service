package com.hub.backend.common.config;

import io.swagger.v3.oas.models.Components;
import io.swagger.v3.oas.models.OpenAPI;
import io.swagger.v3.oas.models.info.Contact;
import io.swagger.v3.oas.models.info.Info;
import io.swagger.v3.oas.models.info.License;
import io.swagger.v3.oas.models.security.SecurityRequirement;
import io.swagger.v3.oas.models.security.SecurityScheme;
import io.swagger.v3.oas.models.servers.Server;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

import java.util.List;

/**
 * OpenAPI metadata for the documentation console.
 *
 * <p>The document is generated by springdoc and is served by this application with no extra
 * profile and nothing in front of it:</p>
 * <ul>
 *   <li>{@code /doc.html} — Knife4j, the <em>only</em> console: Chinese first, with request
 *       debugging and offline export (static assets from the {@code knife4j-openapi3-ui}
 *       webjar);</li>
 *   <li>{@code /v3/api-docs} — the raw document, which is also what {@code mvnw -Popenapi verify}
 *       exports to {@code target/openapi/openapi.json}.</li>
 * </ul>
 *
 * <p>Swagger UI is not on the classpath at all. springdoc is pulled in through
 * {@code springdoc-openapi-starter-webmvc-api} rather than {@code -webmvc-ui}, so there is no
 * second console to keep in step with this one or with the bearer scheme below. See {@code pom.xml}.</p>
 *
 * <p>Endpoints are grouped with Chinese {@code @Tag} annotations on the controllers rather than
 * with {@link org.springdoc.core.models.GroupedOpenApi} beans. Grouped documents are served under
 * {@code /v3/api-docs/{group}} and leave {@code /v3/api-docs} empty, which would break the contract
 * export and the tests asserting against it. Tags give the same sidebar grouping while keeping a
 * single aggregated document.</p>
 *
 * <p>The security scheme is a real bearer token because the console has to be able to call the
 * endpoints: this service reads {@code Authorization: Bearer <accessToken>}. It used to be declared
 * as an {@code apiKey} header literally named {@code Token}, which nothing here ever reads, so the
 * Authorize button produced requests that were rejected with a 401.</p>
 */
@Configuration
public class OpenApiConfig {

    /** Name of the security scheme used for the platform access token. */
    public static final String SECURITY_SCHEME_BEARER = "bearerAuth";

    @Bean
    public OpenAPI backendOpenApi() {
        return new OpenAPI()
                .info(new Info()
                        .title("后端服务接口文档")
                        .description("""
                                多站点 AI 对话后端：对话、会话、模型目录、图片生成、文件、鉴权与后台管理。

                                **鉴权**
                                - 需要身份的接口传 `Authorization: Bearer <accessToken>`；点击右上角
                                  Authorize 填令牌后即可在本页调试。
                                - 令牌由 `POST /api/v1/auth/login` 或 `/api/v1/auth/register` 签发。
                                - 请求接口只接受 Bearer 令牌，不接受 `X-User-Id`，也不会回退到演示账号。

                                **站点**
                                - 站点由请求头 `app-name` 指定，其次按 Host 匹配，最后落到默认站点。
                                  调试多站点数据时请显式带上该头。

                                **调试提示**
                                - `POST /api/v1/chat/stream` 返回 SSE，请用支持流式输出的客户端；
                                  本页的 Try it out 只能看到一次性结果。
                                - 后台接口需要请求头 `X-Admin-Key`；未配置管理密钥时全部拒绝。
                                - 上游网关回 `400` / `413` / `422` / `429` 时，状态码原样透传，`message`
                                  是上游那句可读原因（内容审核拒绝就在这一类，前端应直接展示）；
                                  上游 5xx、不可达，或 401/403/404（属于服务端与上游之间的问题）
                                  一律折叠成 `502`。错误信息已截断且不含密钥。

                                **错误码**
                                - `ApiError.code` 是业务码，不是 HTTP 状态码的重复。前端按码归类，不要拿
                                  关键词猜原因——那正是「正常提示词被判内容审核」的根源。
                                - 取值：`CONTENT_BLOCKED` / `INSUFFICIENT_QUOTA` / `INVALID_INPUT` /
                                  `CONFIRM_PASSWORD` / `AUTH_EXPIRED` / `FORBIDDEN` /
                                  `LOGIN_SYNC_REQUIRED` / `MODEL_UNAVAILABLE` / `TIMEOUT` /
                                  `RATE_LIMITED` / `RESULT_MISSING` / `UPSTREAM_FAILED` /
                                  `SERVICE_UNAVAILABLE` / `BUSY` / `NOT_FOUND` / `CONFLICT` /
                                  `PAYLOAD_TOO_LARGE` / `UNKNOWN`。
                                - 码一旦发布即当作契约：只增不改名，语义变了要换新码。
                                """)
                        .version("v1")
                        .contact(new Contact().name("Backend Service").email("dev@example.com"))
                        .license(new License().name("Proprietary")))
                .servers(List.of(
                        new Server().url("/").description("当前服务"),
                        new Server().url("http://localhost:8080").description("本地开发")))
                .components(new Components().addSecuritySchemes(SECURITY_SCHEME_BEARER,
                        new SecurityScheme()
                                .type(SecurityScheme.Type.HTTP)
                                .scheme("bearer")
                                .bearerFormat("JWT")
                                .description("登录后拿到的 accessToken，形如 `Authorization: Bearer eyJ...`")))
                .addSecurityItem(new SecurityRequirement().addList(SECURITY_SCHEME_BEARER));
    }
}
