    public String skeleton() {
        return skeleton;
    }

    /**
     * 按标签查找；未知标签回落到「论文助手」，与模板引擎的缺省分支保持一致。
     * 空值同样回落，这样老客户端不传 {@code paperType} 也不会报错。
     */
    public static PaperTypeProfile byLabel(String label) {
        if (label == null || label.isBlank()) {
            return THESIS_ASSISTANT;
        }
        String wanted = label.strip();
        for (PaperTypeProfile profile : values()) {
            if (profile.label.equals(wanted)) {
                return profile;
            }
        }
        return THESIS_ASSISTANT;
    }
